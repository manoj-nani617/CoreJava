package com.techouts.Assessment;

public class PrimitativeDataTypes {
    public static void main(String[] args) {
        //  DATA TYPES DETERMINES THE TYPE OF VALUE A VARIABLE CAN HOLD.
        // PRIMITIVE DATA TYPES ARE LISTED BELOW

        //SHORT IS PRIMITIVE DATA TYPE USED TO STORE WHOLE NUMBERS AND DEFAULT VALUES IS 0
        short shortVar = 10;
        System.out.println(shortVar);

        //BYTE IS PRIMITIVE DATA TYPE USED TO STORE WHOLE NUMBERS AND DEFAULT VALUES IS 0
        byte byteVar = 10;
        System.out.println(byteVar);

        //INT IS PRIMITIVE DATA TYPE USED TO STORE WHOLE NUMBERS AND DEFAULT VALUES IS 0
        int intVar = 10;
        System.out.println(intVar);

        //LONG IS PRIMITIVE DATA TYPE USED TO STORE WHOLE NUMBERS AND DEFAULT VALUES IS 0
        long longVar = 10L;
        System.out.println(longVar);

        //FLOAT IS PRIMITIVE DATA TYPE USED TO STORE DECIMAL NUMBERS AND DEFAULT VALUES IS 0.Of
        float floatVar = 10.00f;
        System.out.println(floatVar);

        //DOUBLE IS PRIMITIVE DATA TYPE USED TO STORE DECIMAL NUMBERS AND DEFAULT VALUES IS 0.O
        double doubleVar = 10.00;
        System.out.println(doubleVar);


        //BOOLEAN IS PRIMITIVE DATA TYPE USED TO STORE TRUE OR FALSE AND DEFAULT VALUES IS FALSE
        boolean boolVar = false;
        System.out.println(boolVar);

        //CHAR IS PRIMITIVE DATA TYPE USED TO STORE SINGLE CHARACTER AND DEFAULT VALUES IS NULL CHARACTER
        char charVar = 'c';
        System.out.println(charVar);


    }
}
