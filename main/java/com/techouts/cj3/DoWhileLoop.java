package com.techouts.cj3;

public class DoWhileLoop {
    public static void main(String[] args) {
//        A do-while loop runs at least once, even if the condition is false.
//        do {
//            // code to execute
//        } while (condition);
        int i = 0;

        do {
            System.out.println(i);
            i++;
        } while (i < 5);

    }
}
